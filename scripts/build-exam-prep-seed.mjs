// Builds supabase/seeds/exam-prep.sql (the Pharmacy Exam Prep course) from the exported
// question bank in supabase/seeds/source/exam-prep.json (prompts/05-quizzes-and-exam-prep.md).
// Run: node scripts/build-exam-prep-seed.mjs   then   npm run db:push
//
// Ids are md5() of readable keys, so the seed can run again without duplicating rows.
// A question is skipped (and listed) unless it has a prompt, at least 2 answers with text,
// and exactly one correct answer. Positions keep the source order, so ids stay stable.

import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "supabase/seeds/source/exam-prep.json";
const OUTPUT = "supabase/seeds/exam-prep.sql";
const COURSE = "pharmacy-exam-prep";

const { topics } = JSON.parse(readFileSync(SOURCE, "utf8"));

const clean = (value) => {
  const text = typeof value === "string" ? value.trim() : "";
  return text.length > 0 ? text : null;
};
const sql = (value) => (value === null ? "null" : `'${value.replaceAll("'", "''")}'`);
const id = (key) => `md5(${sql(key)})::uuid`;

const lines = [
  "-- Generated by scripts/build-exam-prep-seed.mjs from supabase/seeds/source/exam-prep.json.",
  "-- Do not edit by hand: change the source or the script and run it again.",
  "",
  "insert into public.tutors (id, name, headline, bio, avatar_url) values",
  `  (${id("tutor:syllo-pharmacy")}, 'Syllo Pharmacy Team', 'Pharmacy exam practice',`,
  "   'Multiple-choice practice across every clinical topic, with an explanation for most answers.',",
  "   'https://picsum.photos/seed/syllo-tutor-pharmacy/200/200')",
  "on conflict (id) do nothing;",
  "",
  "insert into public.courses (id, slug, title, subtitle, description, cover_image_url, category, level, tutor_id, is_published) values",
  `  (${id(`course:${COURSE}`)}, ${sql(COURSE)}, 'Pharmacy Exam Prep',`,
  "   'Practice questions for every clinical topic',",
  `   ${sql(
    `Prepare for your pharmacy exams with ${0} multiple-choice questions across ${topics.length} topics, from cardiovascular to calculations. Each topic is a chapter with its own quiz, and most answers come with an explanation.`,
  )},`,
  `   'https://picsum.photos/seed/syllo-${COURSE}/800/450', 'Healthcare', 'intermediate', ${id("tutor:syllo-pharmacy")}, true)`,
  "on conflict (id) do nothing;",
  "",
];

const report = { topics: 0, questions: 0, answers: 0, skipped: [] };

topics.forEach((topic, topicIndex) => {
  const chapter = topicIndex + 1;
  const chapterKey = `${COURSE}:${chapter}`;
  report.topics += 1;

  lines.push(`-- ${chapter}. ${topic.name}`);
  lines.push("insert into public.chapters (id, course_id, position, title) values");
  lines.push(`  (${id(`chapter:${chapterKey}`)}, ${id(`course:${COURSE}`)}, ${chapter}, ${sql(topic.name)})`);
  lines.push("on conflict (id) do nothing;");
  lines.push("insert into public.quizzes (id, chapter_id, title, position, is_preview) values");
  lines.push(
    `  (${id(`quiz:${chapterKey}`)}, ${id(`chapter:${chapterKey}`)}, ${sql(topic.name)}, 1, ${chapter === 1 ? "true" : "false"})`,
  );
  lines.push("on conflict (id) do nothing;");

  const questionRows = [];
  const answerRows = [];
  topic.questions.forEach((question, questionIndex) => {
    const position = questionIndex + 1;
    const prompt = clean(question.prompt);
    const answers = (question.answers ?? []).map((answer) => ({ text: clean(answer.text), correct: answer.correct === true }));
    const correct = answers.filter((answer) => answer.correct).length;
    const problem = !prompt
      ? "no prompt"
      : answers.length < 2 || answers.some((answer) => !answer.text)
        ? "fewer than 2 answers, or an empty answer"
        : correct !== 1
          ? `${correct} correct answers`
          : null;
    if (problem) {
      report.skipped.push(`${topic.name} #${position}: ${problem}${prompt ? ` (${prompt.slice(0, 70)})` : ""}`);
      return;
    }
    const questionKey = `${chapterKey}:${position}`;
    questionRows.push(
      `  (${id(`question:${questionKey}`)}, ${id(`quiz:${chapterKey}`)}, ${position}, ${sql(prompt)}, ${sql(clean(question.explanation))}, ${sql(clean(question.referenceUrl))})`,
    );
    answers.forEach((answer, answerIndex) => {
      answerRows.push(
        `  (${id(`answer:${questionKey}:${answerIndex + 1}`)}, ${id(`question:${questionKey}`)}, ${answerIndex + 1}, ${sql(answer.text)}, ${answer.correct})`,
      );
    });
    report.questions += 1;
    report.answers += answers.length;
  });

  if (questionRows.length > 0) {
    lines.push("insert into public.quiz_questions (id, quiz_id, position, prompt, explanation, reference_url) values");
    lines.push(questionRows.join(",\n"));
    lines.push("on conflict (id) do nothing;");
    lines.push("insert into public.quiz_answers (id, question_id, position, text, is_correct) values");
    lines.push(answerRows.join(",\n"));
    lines.push("on conflict (id) do nothing;");
  }
  lines.push("");
});

// The course description states the real number of questions imported.
const output = lines.join("\n").replace("with 0 multiple-choice questions", `with ${report.questions.toLocaleString("en-GB")} multiple-choice questions`);
writeFileSync(OUTPUT, output);

console.log(`Wrote ${OUTPUT}: ${report.topics} chapters/quizzes, ${report.questions} questions, ${report.answers} answers.`);
if (report.skipped.length > 0) {
  console.log(`Skipped ${report.skipped.length} question(s):`);
  for (const line of report.skipped) console.log(`  - ${line}`);
}

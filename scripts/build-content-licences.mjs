// Writes src/lib/content-licences.ts (prompts/19): every course-content source with its
// copyright, licence, link and required note, plus the full licence text of MIT, BSD-3 and PSF
// sources (those licences require the notice to travel with the material). The texts are the
// licence files read at each pin by scripts/fetch-course-sources.mjs (run that first).
//
//   node scripts/build-content-licences.mjs
// (build-course-content-seed.mjs also runs this.)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { CACHE, LOCK, loadRegistry } from "./course-content/sources.mjs";

const OUTPUT = path.join(process.cwd(), "src/lib/content-licences.ts");

export function buildContentLicences() {
  const registry = loadRegistry();
  const lock = existsSync(LOCK) ? JSON.parse(readFileSync(LOCK, "utf8")) : { sources: {} };
  const missing = [];
  const entries = Object.entries(registry.sources).map(([id, source]) => {
    let licenceText = null;
    if (source.fullLicenceText) {
      const file = path.join(CACHE, "licences", `${id}.txt`);
      if (existsSync(file)) licenceText = readFileSync(file, "utf8").trim();
      else missing.push(id);
    }
    return {
      id,
      title: source.title,
      copyright: source.copyright,
      licence: source.licence,
      licenceUrl: source.licenceUrl,
      attributionNote: source.attributionNote ?? null,
      role: source.role === "link-only" ? "further_reading" : "adapted",
      repo: source.repo,
      pin: lock.sources?.[id]?.rev ?? source.pin,
      licenceText,
    };
  });
  for (const [id, dataset] of Object.entries(registry.datasets ?? {})) {
    entries.push({
      id,
      title: dataset.title,
      copyright: "Transport for London",
      licence: dataset.licence,
      licenceUrl: dataset.licenceUrl,
      attributionNote: dataset.credit,
      role: "adapted",
      repo: dataset.source,
      pin: dataset.dateRange ?? "",
      licenceText: null,
    });
  }
  if (missing.length) throw new Error(`Missing licence texts (run fetch-course-sources.mjs): ${missing.join(", ")}`);

  const out = `// Generated by scripts/build-content-licences.mjs from supabase/seeds/source/course-sources.json
// and the licence files read at each pinned commit. Do not edit by hand.

export type ContentSource = {
  id: string;
  title: string;
  copyright: string;
  licence: string;
  licenceUrl: string;
  /** A statement the licence requires (OGL), or the credit wording a source asks for. */
  attributionNote: string | null;
  role: "adapted" | "further_reading";
  repo: string;
  /** The commit (or dataset range) the material was taken from. */
  pin: string;
  /** The full licence text, for licences that require the notice to travel with the material. */
  licenceText: string | null;
};

export const CONTENT_SOURCES: ContentSource[] = ${JSON.stringify(entries, null, 2)};
`;
  writeFileSync(OUTPUT, out);
  return { sources: entries.length, withText: entries.filter((e) => e.licenceText).length };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = buildContentLicences();
  console.log(`Wrote src/lib/content-licences.ts: ${result.sources} sources, ${result.withText} full licence texts.`);
}
